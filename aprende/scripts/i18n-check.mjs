
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
let dir = null;
let write = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--dir') { dir = args[++i]; }
  else if (args[i] === '--write') { write = true; }
}

const root = dir ? resolve(dir) : resolve(dirname(fileURLToPath(import.meta.url)), '..');
const esPath = resolve(root, 'i18n', 'es.json');
const enPath = resolve(root, 'i18n', 'en.json');
const dtsPath = resolve(root, 'src', 'core', 'i18n-keys.d.ts');

function load(p) {
  return JSON.parse(readFileSync(p, 'utf8'));
}

const es = load(esPath);
const en = load(enPath);
const esKeys = Object.keys(es).sort();
const enKeys = Object.keys(en).sort();

const missingInEn = esKeys.filter((k) => !enKeys.includes(k));
const missingInEs = enKeys.filter((k) => !esKeys.includes(k));

if (missingInEn.length || missingInEs.length) {
  console.error('i18n key parity failed.');
  if (missingInEn.length) console.error('Missing in en.json:', missingInEn.join(', '));
  if (missingInEs.length) console.error('Missing in es.json:', missingInEs.join(', '));
  process.exit(1);
}

// plural group check: for any key ending in .one/.other, counterpart must exist in same file
function checkPluralForms(keys, label) {
  const bases = new Set();
  for (const k of keys) {
    const m = k.match(/^(.*)\.(one|other|few|many|zero)$/);
    if (m) bases.add(m[1]);
  }
  for (const base of bases) {
    if (!keys.includes(`${base}.one`)) { console.error(`${label}: missing ${base}.one`); process.exit(1); }
    if (!keys.includes(`${base}.other`)) { console.error(`${label}: missing ${base}.other`); process.exit(1); }
  }
}
checkPluralForms(esKeys, 'es.json');
checkPluralForms(enKeys, 'en.json');

// generated type includes catalog keys plus plural bases
const pluralBases = new Set();
for (const k of esKeys) {
  const m = k.match(/^(.*)\.(one|other|few|many|zero)$/);
  if (m) pluralBases.add(m[1]);
}
const typeKeys = [...new Set([...esKeys, ...pluralBases])].sort();

const generated = `// generated by scripts/i18n-check.mjs\nexport type I18nKey = ${typeKeys.map((k) => JSON.stringify(k)).join(' | ')};\n`;

if (write) {
  writeFileSync(dtsPath, generated);
  console.log(`i18n types written: ${typeKeys.length} keys`);
} else {
  if (!existsSync(dtsPath)) {
    console.error('i18n-keys.d.ts missing; run npm run i18n:types');
    process.exit(1);
  }
  const committed = readFileSync(dtsPath, 'utf8');
  if (committed !== generated) {
    console.error('i18n-keys.d.ts is stale; run npm run i18n:types');
    process.exit(1);
  }
  console.log(`i18n check ok: ${typeKeys.length} keys`);
}
