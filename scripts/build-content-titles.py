"""Writes web/content-titles.js: the human names the staff console shows for lesson content (lesson and step titles,
a short English line for each item, the "Tus datos" questions, the document summaries). The console's API lists
entries by code id only; this file turns will.1.2 into "What a will does: A typed will is signed by you...".
Run after changing aprende/content: python scripts/build-content-titles.py"""
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "aprende" / "content"
OUT = ROOT / "web" / "content-titles.js"


def short(text, limit=90):
    text = " ".join(str(text or "").split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def item_line(item):
    en = item.get("en") or {}
    for field in ("prompt", "statement", "text", "story"):
        if en.get(field):
            return short(en[field])
    return ""


def build():
    lessons, steps, items = {}, {}, {}
    for path in sorted((CONTENT / "lessons").glob("*.yaml")):
        lesson = yaml.safe_load(path.read_text(encoding="utf-8"))
        lessons[lesson["id"]] = lesson["title"]["en"]
        for step in lesson.get("steps") or []:
            steps[step["id"]] = step["title"]["en"]
            for item in step.get("items") or []:
                items[item["id"]] = [item["kind"], item_line(item)]
    datos = {q["id"]: short(q["en"]) for q in yaml.safe_load((CONTENT / "datos.yaml").read_text(encoding="utf-8"))}
    summaries = {f"{doc}.{a['article']}": short(a["en"]) for doc, arts in
                 yaml.safe_load((CONTENT / "summaries.yaml").read_text(encoding="utf-8")).items() for a in arts}
    data = {"lessons": lessons, "steps": steps, "items": items, "datos": datos, "summaries": summaries}
    return ("// Generated by scripts/build-content-titles.py from aprende/content. Do not edit by hand.\n"
            "const CONTENT_TITLES = " + json.dumps(data, ensure_ascii=False, indent=0, sort_keys=True) + ";\n")


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
